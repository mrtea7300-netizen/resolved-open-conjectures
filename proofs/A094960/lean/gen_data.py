#!/usr/bin/env python3
"""Generate Kellner/Data.lean: the numbers that the kernel-checked finite check runs on.

Nothing in the Lean proof trusts this script. Lean re-checks every property it uses:
that the listed numbers are prime (one gcd with 700! or 40! each), that the lists are
increasing, and that the window criterion holds along the chain.

Output:
  M700          = 700!  (Lean checks `M700 = Nat.factorial 700`)
  smallPrimes   = the primes in [17, 1600)
  chains        = a list of pairs (stop, primes): consecutive pieces of an increasing chain
                  of primes q_0 = 1361 < q_1 < ... such that for every q_i below the last stop
                  there is k with K(q_i, q_{i+k} - q_i) + 4 <= k, where
                  K(F, S) = floor((S^2 + 2F) / (F + S)).
                  Then every F in [q_i, q_{i+1}) has K(F, S) + 4 primes in (F, F + S] for
                  S = q_{i+k} - F (Lean proves this implication).

Usage: python gen_data.py   (writes Kellner/Data.lean next to this file; about 1 s)
"""
import math
import os

START = 1361          # first prime of the chain; all F >= START are covered by the chain
LIMIT = 468049        # the chain must cover every F < LIMIT
SMALL_HI = 1600
TAIL = 60             # how many chain elements beyond `stop` a piece carries
PIECE = 500           # chain elements per piece


def sieve(n):
    s = bytearray([1]) * (n + 1)
    s[0] = s[1] = 0
    for i in range(2, math.isqrt(n) + 1):
        if s[i]:
            s[i * i :: i] = bytearray(len(s[i * i :: i]))
    return [i for i in range(n + 1) if s[i]]


def K(F, S):
    return (S * S + 2 * F) // (F + S)


def good_from(q, rest):
    """The Lean function `goodFrom q rest 0`."""
    for j, r in enumerate(rest):
        if K(q, r - q) + 4 <= j + 1:
            return True
    return False


def chain_ok(stop, lst):
    """The Lean function `chainOK stop lst`."""
    for i, q in enumerate(lst):
        if stop <= q:
            return True
        if not good_from(q, lst[i + 1 :]):
            return False
    return False


def main():
    primes = sieve(LIMIT + 20000)
    big = [p for p in primes if p >= START]
    # initial sparse selection: about 7 chain elements per window of length sqrt(q)
    sel = set()
    cur = START
    idx = 0
    while cur < LIMIT + 8000:
        sel.add(cur)
        step = max(1, math.isqrt(cur) // 8)
        # largest prime <= cur + step, else the next prime
        j = idx
        while j + 1 < len(big) and big[j + 1] <= cur + step:
            j += 1
        if j == idx:
            j = idx + 1
        idx = j
        cur = big[idx]
    # repair: where the criterion fails, add every prime in the next 2 sqrt(q)
    while True:
        chain = sorted(sel)
        bad = [q for i, q in enumerate(chain)
               if q < LIMIT + 2000 and not good_from(q, chain[i + 1 : i + 1 + TAIL])]
        if not bad:
            break
        for q in bad:
            hi = q + 2 * math.isqrt(q) + 20
            sel.update(p for p in big if q <= p <= hi)
    chain = sorted(sel)
    last = next(i for i, q in enumerate(chain) if q >= LIMIT)
    cuts = list(range(0, last, PIECE)) + [last]
    pieces = []
    for a, b in zip(cuts, cuts[1:]):
        stop = chain[b]
        lst = chain[a : b + TAIL]
        assert chain_ok(stop, lst), (a, b)
        assert all(700 < q < 701 * 701 for q in lst)
        pieces.append((stop, lst))
    assert pieces[0][1][0] == START and pieces[-1][0] >= LIMIT
    for (s0, _), (_, l1) in zip(pieces, pieces[1:]):
        assert l1[0] == s0

    small = [p for p in primes if 17 <= p < SMALL_HI]

    def fmt(lst, indent="  "):
        lines, line = [], indent + "["
        for i, x in enumerate(lst):
            tok = str(x) + ("," if i + 1 < len(lst) else "]")
            if len(line) + len(tok) + 1 > 100:
                lines.append(line)
                line = indent + " " + tok
            else:
                line += (" " if line.strip() != "[" else "") + tok
        lines.append(line)
        return "\n".join(lines)

    out = []
    out.append("/-")
    out.append("GENERATED by `gen_data.py` (do not edit by hand). Plain data: no proofs here.")
    out.append("Every property of these numbers that the proof uses is checked by the Lean kernel in")
    out.append("`Kellner/FiniteKernel.lean`.")
    out.append("-/")
    out.append("import Mathlib.Data.Nat.Factorial.Basic")
    out.append("")
    out.append("namespace Kellner.Data")
    out.append("")
    out.append("/-- `700!` (checked in `FiniteKernel.lean`). -/")
    out.append("def M700 : ℕ :=")
    out.append("  " + str(math.factorial(700)))
    out.append("")
    out.append(f"/-- The primes in `[17, {SMALL_HI})`. -/")
    out.append("def smallPrimes : List ℕ :=")
    out.append(fmt(small))
    out.append("")
    for i, (stop, lst) in enumerate(pieces):
        out.append(f"/-- Piece {i} of the chain: from {lst[0]} up to (not including) {stop}, "
                   f"plus {TAIL} more elements. -/")
        out.append(f"def chain{i} : List ℕ :=")
        out.append(fmt(lst))
        out.append("")
    out.append("/-- The pieces of the chain with their stopping points. -/")
    out.append("def chains : List (ℕ × List ℕ) :=")
    out.append("  [" + ",\n   ".join(f"({stop}, chain{i})" for i, (stop, _) in enumerate(pieces)) + "]")
    out.append("")
    out.append("end Kellner.Data")
    out.append("")
    path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "Kellner", "Data.lean")
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out))
    print(f"chain: {len(chain)} primes selected, {last} below the last stop {pieces[-1][0]}; "
          f"{len(pieces)} pieces; smallPrimes: {len(small)}; wrote {path} "
          f"({os.path.getsize(path)} bytes)")


if __name__ == "__main__":
    main()
